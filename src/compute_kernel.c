#include "compute_kernel.h"
#include <fenv.h>
#include <float.h>
#include <string.h>

void cm_seed_integer(uint64_t state[4]) {
    const uint64_t seeds[4] = {UINT64_C(0x123456789abcdef1), UINT64_C(0xfedcba9876543211),
                              UINT64_C(0x3141592653589793), UINT64_C(0x2718281828459045)};
    memcpy(state, seeds, sizeof(seeds));
}

void cm_seed_float(double state[4]) {
    const double seeds[4] = {0.125, 0.25, 0.375, 0.625};
    memcpy(state, seeds, sizeof(seeds));
}

/* These kernels are compiled in a separate translation unit, without LTO,
 * vectorization, fast math or contraction. No architecture-dependent path,
 * volatile memory bottleneck, libm, guessed clock frequency or PMU dependency.
 */
void cm_integer(uint64_t iterations, uint64_t state[4]) {
    uint64_t a = state[0], b = state[1], c = state[2], d = state[3];
#define STEP(x) do { x ^= x << 13; x ^= x >> 7; x ^= x << 17; } while (0)
    for (uint64_t i = 0; i < iterations; ++i) {
        STEP(a); STEP(b); STEP(c); STEP(d);
    }
#undef STEP
    state[0] = a; state[1] = b; state[2] = c; state[3] = d;
}

void cm_float(uint64_t iterations, double state[4]) {
    double a = state[0], b = state[1], c = state[2], d = state[3];
    for (uint64_t i = 0; i < iterations; ++i) {
        a = (a * (1.0 - a)) * 3.75;
        b = (b * (1.0 - b)) * 3.75;
        c = (c * (1.0 - c)) * 3.75;
        d = (d * (1.0 - d)) * 3.75;
    }
    state[0] = a; state[1] = b; state[2] = c; state[3] = d;
}

int cm_selftest(void) {
#if defined(__FAST_MATH__) || FLT_RADIX != 2 || DBL_MANT_DIG != 53 || DBL_MAX_EXP != 1024 || FLT_EVAL_METHOD != 0
    return 0;
#else
    if (sizeof(double) != sizeof(uint64_t) || fegetround() != FE_TONEAREST) return 0;
    uint64_t ints[4]; double floats[4];
    /* Independent reference vectors: Python uint64-masked recurrence and
     * IEEE binary64 operations, not values generated by these C functions. */
    const uint64_t expected_i[4] = {UINT64_C(0xba0847eea8ebd0e2), UINT64_C(0x61c340a772c1322f),
                                  UINT64_C(0x74453ef8563903c2), UINT64_C(0xf1a9f1feb0726191)};
    const uint64_t expected_f[4] = {UINT64_C(0x3fd83a8dc009a401), UINT64_C(0x3fec704b7f98e801),
                                  UINT64_C(0x3fd94443dcc94d05), UINT64_C(0x3fd94443dcc94d05)};
    cm_seed_integer(ints); cm_seed_float(floats);
    cm_integer(64, ints); cm_float(64, floats);
    for (int i = 0; i < 4; ++i) {
        uint64_t bits;
        memcpy(&bits, &floats[i], sizeof(bits));
        if (ints[i] != expected_i[i] || bits != expected_f[i]) return 0;
    }
    return 1;
#endif
}
